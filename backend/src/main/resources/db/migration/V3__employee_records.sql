CREATE TABLE employees (
    id BIGINT NOT NULL AUTO_INCREMENT,
    employee_number VARCHAR(32) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    work_email VARCHAR(254) NOT NULL,
    personal_email VARCHAR(254) NULL,
    phone VARCHAR(40) NULL,
    date_of_birth DATE NULL,
    gender VARCHAR(24) NULL,
    address_line_1 VARCHAR(200) NULL,
    address_line_2 VARCHAR(200) NULL,
    city VARCHAR(100) NULL,
    state VARCHAR(100) NULL,
    country VARCHAR(100) NULL,
    postal_code VARCHAR(24) NULL,
    status VARCHAR(24) NOT NULL,
    employment_type VARCHAR(24) NOT NULL,
    date_of_joining DATE NOT NULL,
    emergency_contact_name VARCHAR(160) NULL,
    emergency_contact_phone VARCHAR(40) NULL,
    skills VARCHAR(1000) NULL,
    department_id BIGINT NULL,
    designation_id BIGINT NULL,
    manager_id BIGINT NULL,
    location_id BIGINT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uk_employees_number UNIQUE (employee_number),
    CONSTRAINT uk_employees_work_email UNIQUE (work_email),
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_employees_designation FOREIGN KEY (designation_id) REFERENCES designations (id),
    CONSTRAINT fk_employees_manager FOREIGN KEY (manager_id) REFERENCES employees (id),
    CONSTRAINT fk_employees_location FOREIGN KEY (location_id) REFERENCES locations (id),
    INDEX ix_employees_name (last_name, first_name),
    INDEX ix_employees_department_status (department_id, status),
    INDEX ix_employees_location_status (location_id, status),
    INDEX ix_employees_manager (manager_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE employee_history (
    id BIGINT NOT NULL AUTO_INCREMENT,
    employee_id BIGINT NOT NULL,
    change_type VARCHAR(32) NOT NULL,
    details VARCHAR(1000) NOT NULL,
    effective_date DATE NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_employee_history_employee FOREIGN KEY (employee_id) REFERENCES employees (id),
    INDEX ix_employee_history_employee_date (employee_id, effective_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
